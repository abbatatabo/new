import 'dart:convert';

import 'package:http/http.dart' as http;

import '../data/user_db.dart';

/// Word gloss from Quran.com (fetched on demand, cached for offline use).
class WordGloss {
  final int position;
  final String text;
  final String translation;
  final String transliteration;
  const WordGloss(this.position, this.text, this.translation, this.transliteration);
  Map<String, dynamic> toJson() => {'p': position, 'a': text, 't': translation, 'tr': transliteration};
  factory WordGloss.fromJson(Map<String, dynamic> j) =>
      WordGloss(j['p'] as int, j['a'] as String, j['t'] as String, j['tr'] as String);
}

class ClassicalTafsir {
  final int id;
  final String scholar;
  final String scholarAr;
  final int deathAh;
  final int deathCe;
  final String work;
  const ClassicalTafsir(this.id, this.scholar, this.scholarAr, this.deathAh, this.deathCe, this.work);
}

/// Classical Arabic tafsir works (authors died centuries ago; the works are
/// in the public domain). Text is displayed verbatim from the Quran.com
/// digital edition, with that attribution. No translation or summary is
/// generated by this app.
const classicalTafsirs = [
  ClassicalTafsir(14, 'Ibn Kathir', 'ابن كثير', 774, 1373, "Tafsir al-Qur'an al-'Azim"),
  ClassicalTafsir(15, 'al-Tabari', 'الطبري', 310, 923, "Jami' al-Bayan 'an Ta'wil Ay al-Qur'an"),
  ClassicalTafsir(90, 'al-Qurtubi', 'القرطبي', 671, 1273, "al-Jami' li-Ahkam al-Qur'an"),
  ClassicalTafsir(94, 'al-Baghawi', 'البغوي', 516, 1122, "Ma'alim al-Tanzil"),
];

class TafsirText {
  final ClassicalTafsir work;
  final String verseKey;
  final List<String> coveredKeys; // tafsir may cover a group of verses
  final List<String> paragraphs;
  final String sourceUrl;
  const TafsirText(this.work, this.verseKey, this.coveredKeys, this.paragraphs, this.sourceUrl);
}

class OnlineContentService {
  final UserDb userDb;
  final http.Client client;
  static const _api = 'https://api.quran.com/api/v4';
  OnlineContentService(this.userDb, {http.Client? client}) : client = client ?? http.Client();

  Future<List<WordGloss>?> wordGlosses(int surah, int ayah, {bool allowNetwork = true}) async {
    final key = 'wbw:$surah:$ayah';
    final cached = await userDb.cacheGet(key);
    if (cached != null) {
      return (jsonDecode(cached) as List).map((e) => WordGloss.fromJson((e as Map).cast())).toList();
    }
    if (!allowNetwork) return null;
    try {
      final r = await client
          .get(Uri.parse('$_api/verses/by_key/$surah:$ayah?words=true&word_fields=text_uthmani&language=en'))
          .timeout(const Duration(seconds: 12));
      if (r.statusCode != 200) return null;
      final words = ((jsonDecode(r.body) as Map)['verse'] as Map)['words'] as List;
      final out = <WordGloss>[];
      for (final w in words.cast<Map>()) {
        if (w['char_type_name'] != 'word') continue;
        out.add(WordGloss(
          w['position'] as int,
          (w['text_uthmani'] ?? '') as String,
          ((w['translation'] as Map?)?['text'] ?? '') as String,
          ((w['transliteration'] as Map?)?['text'] ?? '') as String,
        ));
      }
      await userDb.cachePut(key, jsonEncode(out.map((e) => e.toJson()).toList()));
      return out;
    } catch (_) {
      return null;
    }
  }

  Future<TafsirText?> tafsir(ClassicalTafsir work, int surah, int ayah, {bool allowNetwork = true}) async {
    final key = 'tafsir:${work.id}:$surah:$ayah';
    final url = 'https://quran.com/$surah:$ayah/tafsirs/${_slug(work.id)}';
    Map<String, dynamic>? data;
    final cached = await userDb.cacheGet(key);
    if (cached != null) {
      data = jsonDecode(cached) as Map<String, dynamic>;
    } else if (allowNetwork) {
      try {
        final r = await client
            .get(Uri.parse('$_api/tafsirs/${work.id}/by_ayah/$surah:$ayah'))
            .timeout(const Duration(seconds: 15));
        if (r.statusCode != 200) return null;
        final t = (jsonDecode(r.body) as Map)['tafsir'] as Map;
        data = {
          'keys': ((t['verses'] as Map?)?.keys.toList() ?? ['$surah:$ayah']).cast<String>(),
          'html': (t['text'] ?? '') as String,
        };
        await userDb.cachePut(key, jsonEncode(data));
      } catch (_) {
        return null;
      }
    }
    if (data == null) return null;
    final paras = htmlToParagraphs(data['html'] as String);
    if (paras.isEmpty) return null;
    return TafsirText(work, '$surah:$ayah', (data['keys'] as List).cast<String>(), paras, url);
  }

  static String _slug(int id) => switch (id) {
    14 => 'ar-tafsir-ibn-kathir',
    15 => 'ar-tafsir-al-tabari',
    90 => 'ar-tafseer-al-qurtubi',
    94 => 'ar-tafsir-al-baghawi',
    _ => '$id',
  };

  /// Converts the source HTML to plain paragraphs without altering words.
  static List<String> htmlToParagraphs(String html) {
    final withBreaks = html
        .replaceAll(RegExp(r'</p>|<br\s*/?>|</h\d>|</div>', caseSensitive: false), '\n')
        .replaceAll(RegExp(r'<[^>]+>'), '');
    final decoded = withBreaks
        .replaceAll('&nbsp;', ' ')
        .replaceAll('&quot;', '"')
        .replaceAll('&#39;', "'")
        .replaceAll('&lt;', '<')
        .replaceAll('&gt;', '>')
        .replaceAll('&amp;', '&');
    return decoded.split('\n').map((s) => s.trim()).where((s) => s.isNotEmpty).toList();
  }

  /// English tafsir works that are under copyright are linked, never copied.
  static List<(String, String)> externalEnglishTafsir(int surah, int ayah) => [
    ('Ibn Kathir (abridged English, Darussalam) – on Quran.com', 'https://quran.com/$surah:$ayah/tafsirs/en-tafisr-ibn-kathir'),
    ("Ma'arif al-Qur'an (Mufti Muhammad Shafi) – on Quran.com", 'https://quran.com/$surah:$ayah/tafsirs/en-tafsir-maarif-ul-quran'),
    ('Tafsir al-Jalalayn (English, Royal Aal al-Bayt Institute) – altafsir.com', 'https://www.altafsir.com/Tafasir.asp?tMadhNo=0&tTafsirNo=74&tSoraNo=$surah&tAyahNo=$ayah&tDisplay=yes&LanguageID=2'),
  ];
}
